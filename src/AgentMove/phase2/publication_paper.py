from __future__ import annotations

import argparse
import json
from pathlib import Path


DATASETS = ("tist2015", "www2019", "yjmob100k")
LABELS = {
    "tist2015": "TIST2015 (12-city macro)",
    "www2019": "WWW2019-Shanghai",
    "yjmob100k": "YJMob100K-Dataset1",
}


def load(path: Path, expected_gate: str) -> dict:
    if not path.is_file():
        raise FileNotFoundError(f"missing aggregate: {path}")
    payload = json.loads(path.read_text(encoding="utf-8"))
    if payload.get("gate") != expected_gate:
        raise ValueError(f"gate {payload.get('gate')!r} in {path}; expected {expected_gate!r}")
    if payload.get("missing"):
        raise ValueError(f"aggregate still reports {len(payload['missing'])} missing artifacts: {path}")
    missing_datasets = set(DATASETS) - set(payload.get("datasets", {}))
    if missing_datasets:
        raise ValueError(f"missing datasets in {path}: {sorted(missing_datasets)}")
    return payload


def mean(value: dict, digits: int = 4) -> str:
    return f"{float(value['mean']):.{digits}f}"


def metric_row(label: str, name: str, values: dict, metrics: tuple[str, ...]) -> str:
    cells = [label, name] + [mean(values[metric]) for metric in metrics]
    return " & ".join(cells) + r" \\"


def find_test(payload: dict, dataset: str, comparison: str, metric: str) -> dict:
    for row in payload["paired_tests"]:
        if (row.get("dataset"), row.get("comparison"), row.get("metric")) == (
            dataset,
            comparison,
            metric,
        ):
            return row
    raise KeyError(f"missing paired test: {dataset}/{comparison}/{metric}")


def test_values(row: dict) -> tuple[float, list[float], float, bool]:
    effect = float(row.get("effect_favoring_first", row.get("effect")))
    ci = row.get("bootstrap_ci95", row.get("ci95"))
    p = float(row.get("holm_adjusted_p", row.get("holm_p")))
    sig = bool(row.get("significant_at_0.05", row.get("significant")))
    return effect, [float(ci[0]), float(ci[1])], p, sig


def render(rq3: dict, rq4: dict, rq7: dict, rq8: dict) -> str:
    lines = [
        "% Generated by phase2.publication_paper; do not edit numbers manually.",
        r"\begin{table*}[!t]",
        r"\centering",
        r"\caption{Last-query results for knowledge distillation and dual-axis evolution. TIST2015 is an equal-weight macro average over 12 cities; the other datasets average seeds 42--44.}",
        r"\label{tab:rq4_main}",
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        "Dataset & Variant & R@1 & R@5 & R@10 & MRR \\\\",
        r"\midrule",
    ]
    for dataset in DATASETS:
        values = rq4["datasets"][dataset]["variants"]
        for variant in ("E0-ce", "E1-kd", "E5-dual"):
            lines.append(metric_row(LABELS[dataset], variant, values[variant], ("recall@1", "recall@5", "recall@10", "mrr")))
        if dataset != DATASETS[-1]:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]

    lines += [
        r"\begin{table}[!t]",
        r"\centering",
        r"\caption{Paired R@1 effects for RQ4. Positive values favor the first variant; $p_{\mathrm{H}}$ is Holm-adjusted.}",
        r"\label{tab:rq4_tests}",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        "Dataset/contrast & Effect & 95\\% CI & $p_{\\mathrm{H}}$ \\\\",
        r"\midrule",
    ]
    for dataset in DATASETS:
        for short, comparison in (("KD", "E1-kd-vs-E0-ce"), ("Dual", "E5-dual-vs-E1-kd")):
            effect, ci, p, _ = test_values(find_test(rq4, dataset, comparison, "recall@1"))
            lines.append(f"{LABELS[dataset]} ({short}) & {effect:.4f} & [{ci[0]:.4f}, {ci[1]:.4f}] & {p:.4g} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

    lines += [
        r"\begin{table*}[!t]",
        r"\centering",
        r"\caption{All-prefix transition-aware belief refinement. Lower NLL and ECE are better.}",
        r"\label{tab:rq7_main}",
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        "Dataset & Variant & R@1 & MRR & NLL$\\downarrow$ & ECE$\\downarrow$ \\\\",
        r"\midrule",
    ]
    for dataset in DATASETS:
        values = rq7["datasets"][dataset]["variants"]
        for variant in ("B0-static", "B3-dbn"):
            lines.append(metric_row(LABELS[dataset], variant, values[variant], ("recall@1", "mrr", "nll", "ece")))
        if dataset != DATASETS[-1]:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]

    lines += [
        r"\begin{table*}[!t]",
        r"\centering",
        r"\caption{Bounded LLM evidence experiment ($n\leq200$ queries per unit, Qwen2:7b). M3 keeps quantitative evidence only; M4 adds structured LLM evidence.}",
        r"\label{tab:rq3_main}",
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        "Dataset & Variant & R@1 & R@5 & R@10 & MRR \\\\",
        r"\midrule",
    ]
    for dataset in DATASETS:
        values = rq3["datasets"][dataset]["variants"]
        for variant in ("M3-quantitative", "M4-both"):
            lines.append(metric_row(LABELS[dataset], variant, values[variant], ("recall@1", "recall@5", "recall@10", "mrr")))
        if dataset != DATASETS[-1]:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]

    lines += [
        r"\begin{table*}[!t]",
        r"\centering",
        r"\caption{Bounded uncertainty-routing results at the primary validation-selected budget. Random is averaged over 50 budget-matched draws.}",
        r"\label{tab:rq8_main}",
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        "Dataset & Policy & R@1 & MRR & Call rate & Tokens/query \\\\",
        r"\midrule",
    ]
    for dataset in DATASETS:
        values = rq8["datasets"][dataset]["policies"]
        for policy in ("never", "always", "entropy", "random-budget-matched"):
            lines.append(metric_row(LABELS[dataset], policy, values[policy], ("recall@1", "mrr", "llm_call_rate", "tokens_per_query")))
        if dataset != DATASETS[-1]:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Validate Phase-2 evidence and export IEEE LaTeX tables")
    parser.add_argument("--root", type=Path, default=Path("results/phase2/aggregated"))
    parser.add_argument("--limit", type=int, default=200)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--audit-only", action="store_true")
    args = parser.parse_args()

    rq3 = load(args.root / f"rq3_limit-{args.limit}_summary.json", "ready-bounded")
    rq4 = load(args.root / "rq4_summary.json", "ready")
    rq7 = load(args.root / "rq7_summary.json", "ready")
    rq8 = load(args.root / f"rq8_limit-{args.limit}_summary.json", "ready-bounded")
    if args.audit_only:
        print(json.dumps({"gate": "ready", "rqs": ["RQ3", "RQ4", "RQ7", "RQ8"], "limit": args.limit}))
        return
    if args.output is None:
        parser.error("--output is required unless --audit-only is used")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(rq3, rq4, rq7, rq8) + "\n", encoding="utf-8")
    print(json.dumps({"gate": "ready", "output": str(args.output), "limit": args.limit}))


if __name__ == "__main__":
    try:
        main()
    except (FileNotFoundError, KeyError, ValueError) as exc:
        raise SystemExit(f"publication gate failed: {exc}") from None
